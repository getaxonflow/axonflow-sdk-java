  private static String emitContract(Surface s) {
    StringBuilder b = new StringBuilder(header(s));
    b.append(
        Layout.javadoc(
            "",
            Collections.singletonList(
                "Constants naming the contract these types were generated from."),
            Collections.<String>emptyList()));
    b.append("public final class AuthZENContract {\n\n");
    b.append("  private AuthZENContract() {}\n\n");
    b.append(
        Layout.javadoc(
            "  ",
            Arrays.asList(
                "The profile a Policy Enforcement Point negotiates to receive anything beyond the"
                    + " boolean decision.",
                "<p>AuthZEN 1.0's response is a bare boolean. The four-valued state, the"
                    + " obligations, the approval challenge and the safe reason code all ride in"
                    + " the response context and are returned ONLY to a caller that asked for them"
                    + " by version, because handing a partial interpretation to a caller that"
                    + " cannot act on it is worse than handing it the boolean it understands."),
            Collections.<String>emptyList()));
    b.append(assignment("  ", "public static final String PROFILE_V1", "\"" + s.profile + "\""));
    b.append("\n");
    b.append(
        Layout.javadoc(
            "  ",
            Collections.singletonList(
                "The contract version these types were generated from. It is the value the server"
                    + " echoes in {@code AuthZENResponseContext.schemaVersion}."),
            Collections.<String>emptyList()));
    b.append(
        assignment(
            "  ",
            "public static final String SCHEMA_VERSION",
            "\"" + s.contractSchemaVersion + "\""));
    b.append("}\n");
    return b.toString();
  }

  // -------------------------------------------------------------------------
  // Enums
  // -------------------------------------------------------------------------

  /**
   * A closed set of wire values, rendered as a value CLASS rather than a Java {@code enum}.
   *
   * <p>A Java enum cannot carry a value it does not declare, so a value a newer server added after
   * this build would either throw during deserialisation or — with {@code
   * READ_UNKNOWN_ENUM_VALUES_AS_NULL} — become null, and a null operational state read as "not
   * ALLOW" is a decision this build never saw. A value class round-trips the string verbatim and
   * says so through {@code isKnown()}.
   */
  private static String emitEnum(Surface s, EnumDecl e) {
    String name = typeName(e.name);
    Set<String> needed =
        new HashSet<>(
            Arrays.asList(
                "com.fasterxml.jackson.annotation.JsonCreator",
                "com.fasterxml.jackson.annotation.JsonValue",
                "java.util.Arrays",
                "java.util.Collections",
                "java.util.List",
                "java.util.Objects"));

    List<String> classDoc = new ArrayList<>();
    if (!e.doc.isEmpty()) {
      classDoc.add(e.doc);
    }
    classDoc.add("A closed set of values the server may send.");
    classDoc.add(
        "<p>An unrecognised value is not a failure mode, it is a ROUND TRIP: a value a newer server"
            + " added after this build survives decode, re-encode and logging intact instead of"
            + " collapsing onto a neighbouring constant. It is, however, a reason not to branch on"
            + " the value as though it were one of the known ones — use {@link #isKnown()}.");

    StringBuilder b = new StringBuilder(header(s)).append(imports(needed));
    b.append(Layout.javadoc("", classDoc, Collections.<String>emptyList()));
    b.append("public final class ").append(name).append(" {\n\n");

    for (String v : e.values) {
      b.append("  /** {@code ").append(v).append("} */\n");
      b.append(
          assignment(
              "  ",
              "public static final " + name + " " + constantName(v),
              "new " + name + "(\"" + v + "\")"));
      b.append("\n");
    }

    b.append(
        Layout.javadoc(
            "  ",
            Arrays.asList(
                "Every wire value this build knows, in artifact order.",
                "<p>This is the set a refusal names in its {@code supported} list, so it is the"
                    + " list a diagnostic should print rather than one written beside it."),
            Collections.<String>emptyList()));
    b.append(knownWireValues(e.values)).append("\n");

    b.append("  private final String value;\n\n");
    b.append("  private ").append(name).append("(String value) {\n");
    b.append("    this.value = value;\n  }\n\n");

    b.append(
        Layout.javadoc(
            "  ",
            Collections.singletonList(
                "The constant for {@code value}, or a carrier for one this build does not know."),
            Arrays.asList(
                "@param value the wire value",
                "@return the corresponding instance, never null for a non-null input")));
    b.append("  @JsonCreator\n");
    b.append("  public static ").append(name).append(" of(String value) {\n");
    b.append("    if (value == null) {\n      return null;\n    }\n");
    for (String v : e.values) {
      b.append("    if (")
          .append(constantName(v))
          .append(".value.equals(value)) {\n      return ")
          .append(constantName(v))
          .append(";\n    }\n");
    }
    b.append("    return new ").append(name).append("(value);\n  }\n\n");

    b.append(
        Layout.javadoc(
            "  ",
            Collections.singletonList("The wire value."),
            Collections.singletonList("@return the value as the server spells it")));
    b.append("  @JsonValue\n  public String value() {\n    return value;\n  }\n\n");

    b.append(
        Layout.javadoc(
            "  ",
            Arrays.asList(
                "Whether this is a value this build knows.",
                "<p>A false result is not necessarily an error — a newer server may send a value"
                    + " added after this SDK was built. It IS a reason not to treat it as"
                    + " equivalent to any known value."),
            Collections.singletonList(
                "@return true when the value is one of {@link #KNOWN_WIRE_VALUES}")));
    b.append("  public boolean isKnown() {\n    return KNOWN_WIRE_VALUES.contains(value);\n  }\n\n");

    b.append("  @Override\n  public boolean equals(Object other) {\n");
    b.append("    if (this == other) {\n      return true;\n    }\n");
    b.append("    if (!(other instanceof ")
        .append(name)
        .append(")) {\n      return false;\n    }\n");
    b.append("    return value.equals(((").append(name).append(") other).value);\n  }\n\n");
    b.append("  @Override\n  public int hashCode() {\n    return Objects.hash(value);\n  }\n\n");
    b.append("  @Override\n  public String toString() {\n    return value;\n  }\n}\n");
    return b.toString();
  }

  /** Renders {@code KNOWN_WIRE_VALUES}, in whichever of the formatter's shapes fits. */
  private static String knownWireValues(List<String> values) {
    List<String> quoted = new ArrayList<>();
    for (String v : values) {
      quoted.add("\"" + v + "\"");
    }
    String lhs = "  public static final List<String> KNOWN_WIRE_VALUES =\n";
    String inline =
        "      Collections.unmodifiableList(Arrays.asList(" + String.join(", ", quoted) + "));";
    if (inline.length() <= Layout.MAX_WIDTH) {
      return lhs + inline + "\n";
    }
    StringBuilder b = new StringBuilder(lhs);
    b.append("      Collections.unmodifiableList(\n");
    b.append("          Arrays.asList(\n");
    for (int i = 0; i < quoted.size(); i++) {
      b.append("              ").append(quoted.get(i));
      b.append(i == quoted.size() - 1 ? "));" : ",").append("\n");
    }
    return b.toString();
  }

