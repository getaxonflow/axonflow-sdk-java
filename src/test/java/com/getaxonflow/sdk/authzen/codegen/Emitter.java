  private static String emitType(Surface s, TypeDecl t) {
    String name = typeName(t.name);
    Set<String> needed = new HashSet<>();
    needed.add("com.fasterxml.jackson.annotation.JsonInclude");
    needed.add("com.fasterxml.jackson.annotation.JsonProperty");
    for (FieldDecl f : t.fields) {
      collectImports(f.type, needed);
    }

    StringBuilder body = new StringBuilder();
    body.append(
        Layout.javadoc(
            "",
            Collections.singletonList(
                t.doc.isEmpty() ? "Part of the AuthZEN wire surface." : t.doc),
            Collections.<String>emptyList()));
    body.append("@JsonInclude(JsonInclude.Include.NON_NULL)\n");
    body.append("public final class ").append(name).append(" {\n\n");

    for (FieldDecl f : t.fields) {
      List<String> doc = new ArrayList<>();
      if (!f.doc.isEmpty()) {
        doc.add(f.doc);
      }
      if (!f.constant.isEmpty()) {
        doc.add("The only value the server sends is {@code " + f.constant + "}.");
      }
      if (!doc.isEmpty()) {
        body.append(Layout.javadoc("  ", doc, Collections.<String>emptyList()));
      }
      if (!f.required && isCollectionish(f.type)) {
        body.append("  @JsonInclude(JsonInclude.Include.NON_EMPTY)\n");
      }
      body.append("  @JsonProperty(\"").append(f.name).append("\")\n");
      String declaration = "private " + javaType(f) + " " + fieldName(f.name);
      String init = initialiser(f);
      if (init.isEmpty()) {
        body.append("  ").append(declaration).append(";\n\n");
      } else {
        body.append(assignment("  ", declaration, init)).append("\n");
      }
    }

    emitConstructors(body, name, t);
    emitAccessors(body, name, t);
    emitValidate(body, t);

    // The last member already ends with a blank line, and a blank line before
    // the closing brace is one the formatter removes.
    while (body.length() >= 2 && body.charAt(body.length() - 2) == '\n') {
      body.setLength(body.length() - 1);
    }
    body.append("}\n");
    return header(s) + imports(needed) + body;
  }

  private static void emitConstructors(StringBuilder b, String name, TypeDecl t) {
    b.append(
        Layout.javadoc(
            "  ",
            Collections.singletonList(
                "Jackson, and a caller that prefers to set members one at a time."),
            Collections.<String>emptyList()));
    b.append("  public ").append(name).append("() {}\n\n");

    List<FieldDecl> required = new ArrayList<>();
    for (FieldDecl f : t.fields) {
      if (f.required) {
        required.add(f);
      }
    }
    if (required.isEmpty()) {
      return;
    }
    List<String> tags = new ArrayList<>();
    for (FieldDecl f : required) {
      tags.add("@param " + fieldName(f.name) + " the " + f.name);
    }
    b.append(
        Layout.javadoc(
            "  ",
            Arrays.asList(
                "Builds a value carrying every member the contract requires.",
                "<p>Optional members start empty and are set with their fluent setter, so a member"
                    + " added to the contract later becomes a compile error at NO call site that"
                    + " did not want it."),
            tags));
    List<String> params = new ArrayList<>();
    for (FieldDecl f : required) {
      params.add(javaType(f) + " " + fieldName(f.name));
    }
    b.append(Layout.call("  ", "public " + name + "(", params, ") {"));
    for (FieldDecl f : required) {
      String field = fieldName(f.name);
      b.append("    this.").append(field).append(" = ").append(field).append(";\n");
    }
    b.append("  }\n\n");
  }

  private static void emitAccessors(StringBuilder b, String name, TypeDecl t) {
    for (FieldDecl f : t.fields) {
      String field = fieldName(f.name);
      String type = javaType(f);
      String upper = upperFirst(field);
      b.append(
          Layout.javadoc(
              "  ",
              Collections.<String>emptyList(),
              Collections.singletonList("@return the {@code " + f.name + "} member")));
      b.append("  public ").append(type).append(" get").append(upper).append("() {\n");
      b.append("    return ").append(field).append(";\n  }\n\n");

      b.append(
          Layout.javadoc(
              "  ",
              Collections.<String>emptyList(),
              Arrays.asList(
                  "@param " + field + " the {@code " + f.name + "} member",
                  "@return this, for chaining")));
      b.append(
          Layout.call(
              "  ",
              "public " + name + " set" + upper + "(",
              Collections.singletonList(type + " " + field),
              ") {"));
      if ("object".equals(f.type.kind)) {
        // A NULL attribute bag is not an empty one, and accepting null here was
        // a way to delete an unresolved attribute through a public setter:
        // `validate` guards `if (bag != null)`, so a request whose bag held an
        // `unknown` went out complete once somebody nulled the member. The
        // field's own invariant is "never null"; the setter now holds it.
        b.append("    this.")
            .append(field)
            .append(" = ")
            .append(field)
            .append(" == null ? new AttributeMap() : ")
            .append(field)
            .append(";\n");
      } else {
        b.append("    this.").append(field).append(" = ").append(field).append(";\n");
      }
      b.append("    return this;\n  }\n\n");
    }
  }

  /**
   * Renders the checks the type system cannot carry.
   *
   * <p>EVERY type gets one, including types with no constraint of their own. A type whose members
   * are all optional still OWNS the validation of those members: skipping it because "there is
   * nothing to check here" is how a parent reports OK while a child carries a violation the server
   * refuses.
   */
  private static void emitValidate(StringBuilder b, TypeDecl t) {
    b.append(
        Layout.javadoc(
            "  ",
            Arrays.asList(
                "Refuses this value if it does not carry what the server requires.",
                "<p>{@code at} is the JSON Pointer this value sits at in the envelope, so a refusal"
                    + " names the same member the server would name. Pass {@code \"\"} at the"
                    + " root."),
            Arrays.asList(
                "@param at the JSON Pointer this value sits at",
                "@throws AuthZENRefusedException if a contract rule is not satisfied")));
    b.append("  public void validate(String at) {\n");

    for (List<String> group : t.exactlyOneOf) {
      b.append("    int present = 0;\n");
      for (String m : group) {
        b.append("    if (").append(fieldName(m)).append(" != null) {\n      present++;\n    }\n");
      }
      b.append("    if (present != 1) {\n");
      b.append(
          refusal(
              "MALFORMED_ENVELOPE",
              "at",
              "\"exactly one of "
                  + String.join(" or ", group)
                  + " must be present, \" + present + \" are\""));
      b.append("    }\n");
    }

    for (FieldDecl f : t.fields) {
      String field = fieldName(f.name);
      String pointer = "at + \"/" + f.name + "\"";

      if (f.required) {
        String emptiness = null;
        if ("string".equals(f.type.kind)) {
          emptiness = field + " == null || " + field + ".isEmpty()";
        } else if ("enum".equals(f.type.kind)) {
          emptiness = field + " == null || " + field + ".value().isEmpty()";
        } else if ("ref".equals(f.type.kind)
            || "array".equals(f.type.kind)
            || "bool".equals(f.type.kind)
            || "int".equals(f.type.kind)) {
          // `bool` and `int` are here for the reason javaType explains: a
          // missing required primitive is invisible to both the decoder and any
          // check written against a primitive, and one of them is
          // `obligation.mandatory`.
          emptiness = field + " == null";
        }
        if (emptiness != null) {
          b.append("    if (").append(emptiness).append(") {\n");
          b.append(refusal("INCOMPLETE_EVALUATION", pointer, "\"" + f.name + " is required\""));
          b.append("    }\n");
        }
      }

      // A required string is already refused when empty, so `min_length: 1` on
      // one would emit a branch that can never be taken. An unreachable branch
      // in generated code is a branch no test can cover, and it teaches a reader
      // that the two checks are independent when they are not.
      if (f.minLength > 0 && (!f.required || f.minLength > 1)) {
        b.append("    if (")
            .append(field)
            .append(" != null && ")
            .append(field)
            .append(".length() < ")
            .append(f.minLength)
            .append(") {\n");
        b.append(
            refusal(
                "INCOMPLETE_EVALUATION",
                pointer,
                "\""
                    + f.name
                    + " needs at least "
                    + f.minLength
                    + " character"
                    + (f.minLength == 1 ? "" : "s")
                    + "\""));
        b.append("    }\n");
      }

      if (!f.constant.isEmpty()) {
        if (f.constant.indexOf('"') >= 0 || f.constant.indexOf('\\') >= 0) {
          throw new SurfaceException(
              "const values carrying a quote or a backslash are not supported: " + f.constant);
        }
        b.append("    if (")
            .append(field)
            .append(" != null && !\"")
            .append(f.constant)
            .append("\".equals(")
            .append(field)
            .append(")) {\n");
        b.append(
            refusal(
                "MALFORMED_ENVELOPE",
                pointer,
                "\"" + f.name + " must be " + f.constant + ", got \" + " + field));
        b.append("    }\n");
      }

      if (f.minItems > 0) {
        b.append("    if (")
            .append(field)
            .append(" == null || ")
            .append(field)
            .append(".size() < ")
            .append(f.minItems)
            .append(") {\n");
        b.append(
            refusal(
                "MALFORMED_ENVELOPE",
                pointer,
                "\""
                    + f.name
                    + " needs at least "
                    + f.minItems
                    + " entr"
                    + (f.minItems == 1 ? "y" : "ies")
                    + "\""));
        b.append("    }\n");
      }

      for (String m : f.requiresMembers) {
        b.append("    if (")
            .append(field)
            .append(" != null && ")
            .append(field)
            .append(".get")
            .append(upperFirst(fieldName(m)))
            .append("() == null) {\n");
        b.append(
            refusal(
                "INCOMPLETE_EVALUATION",
                "at + \"/" + f.name + "/" + m + "\"",
                "\"" + f.name + " has no " + m + "; it has no shared base to inherit one from\""));
        b.append("    }\n");
      }

      // Nested validation. Without it a parent reports OK while a child carries
      // a violation the server refuses.
      if ("object".equals(f.type.kind)) {
        // No null guard: the field is initialised to an empty bag and its setter
        // refuses null, so a guard here would only be a place for a future null
        // to hide - and what it would hide is an unresolved attribute.
        b.append("    ").append(field).append(".validate(").append(pointer).append(");\n");
      } else if ("ref".equals(f.type.kind)) {
        b.append("    if (").append(field).append(" != null) {\n      ");
        b.append(field).append(".validate(").append(pointer).append(");\n    }\n");
      } else if ("array".equals(f.type.kind)
          && f.type.items != null
          && "ref".equals(f.type.items.kind)) {
        b.append("    if (").append(field).append(" != null) {\n");
        b.append("      for (int i = 0; i < ").append(field).append(".size(); i++) {\n        ");
        b.append(field).append(".get(i).validate(").append(pointer).append(" + \"/\" + i);\n");
        b.append("      }\n    }\n");
      }
    }
    b.append("  }\n\n");
  }

  /** One {@code throw AuthZENRefusedException.of(...)}, laid out the way the formatter would. */
  private static String refusal(String code, String pointer, String message) {
    return Layout.call(
        "      ",
        "throw AuthZENRefusedException.of(",
        Arrays.asList("AuthZENErrorCode." + code, pointer, message),
        ");");
  }

