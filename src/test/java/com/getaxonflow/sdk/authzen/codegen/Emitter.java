  // Types and names
  // -------------------------------------------------------------------------

  private static void collectImports(TypeRef tr, Set<String> needed) {
    if (tr == null) {
      return;
    }
    if ("array".equals(tr.kind)) {
      needed.add("java.util.List");
      collectImports(tr.items, needed);
    } else if ("map".equals(tr.kind)) {
      needed.add("java.util.Map");
      collectImports(tr.value, needed);
    }
  }

  private static boolean isCollectionish(TypeRef tr) {
    return "array".equals(tr.kind) || "map".equals(tr.kind) || "object".equals(tr.kind);
  }

  private static String initialiser(FieldDecl f) {
    // An attribute bag is never null. An empty bag IS "the caller supplied no
    // attributes", and a null one would add a fourth state to a member whose
    // values already carry three.
    return "object".equals(f.type.kind) ? "new AttributeMap()" : "";
  }

  private static String javaType(FieldDecl f) {
    return javaType(f.type, f.required);
  }

  private static String javaType(TypeRef tr, boolean required) {
    switch (tr.kind) {
      case "string":
        return "String";
      case "bool":
      case "int":
        // ALWAYS boxed, required or not.
        //
        // A primitive for a required member reads as "absent is not a state the
        // contract allows", and that is true of the CONTRACT and false of the
        // decoder. Jackson leaves a missing primitive at its default, so an
        // omitted `obligation.mandatory` decoded to `false`, passed validation
        // (a primitive cannot be null, so there is nothing to check), and
        // `AuthZENDecision.getMandatoryObligations()` returned empty - turning
        // off the one instruction the caller must not ignore, silently. The
        // strict reader cannot help: it catches EXTRA members, never missing
        // ones.
        //
        // Boxed, the missing member is null and the generated validator refuses
        // it by name.
        return "bool".equals(tr.kind) ? "Boolean" : "Integer";
      case "object":
        return "AttributeMap";
      case "enum":
        return typeName(tr.enumName);
      case "ref":
        return typeName(tr.ref);
      case "array":
        return "List<" + javaType(tr.items, true) + ">";
      case "map":
        return "Map<String, " + javaType(tr.value, true) + ">";
      default:
        // Never a default type. An unrecognised kind silently rendered as
        // Object would compile, ship, and accept values the server refuses.
        throw new SurfaceException("unsupported type kind \"" + tr.kind + "\"");
    }
  }

  /**
   * Maps an artifact name onto this SDK's exported name.
   *
   * <p>{@code AuthZEN}, not {@code AuthZen}: these class names are matched LITERALLY against the
   * OpenAPI schema names by {@code scripts/wire_shape/validate.py}, and the specs spell them {@code
   * AuthZENSubject}. A prettier local spelling would make every one of these an unmatched
   * "SDK-only" class, which is exactly the coverage gap that gate exists to report.
   *
   * <p>Every generated type carries the prefix, not only the ones that would collide today. That
   * keeps the rule mechanical: a future collision does not require choosing a new convention under
   * time pressure.
   */
  private static String typeName(String artifactName) {
    String stripped =
        artifactName.startsWith("authzen_")
            ? artifactName.substring("authzen_".length())
            : artifactName;
    return "AuthZEN" + pascal(stripped);
  }

  private static String fieldName(String wire) {
    String camel = camel(wire);
    return isJavaKeyword(camel) ? camel + "Value" : camel;
  }

  private static String constantName(String wireValue) {
    StringBuilder b = new StringBuilder();
    for (String part : wireValue.split("[_.\\-]")) {
      if (part.isEmpty()) {
        continue;
      }
      if (b.length() > 0) {
        b.append('_');
      }
      b.append(part.toUpperCase());
    }
    return b.toString();
  }

  private static String camel(String s) {
    String[] parts = s.split("[_.\\-]");
    StringBuilder b = new StringBuilder();
    for (int i = 0; i < parts.length; i++) {
      if (parts[i].isEmpty()) {
        continue;
      }
      b.append(i == 0 ? parts[i] : upperFirst(parts[i]));
    }
    return b.toString();
  }

  private static String pascal(String s) {
    StringBuilder b = new StringBuilder();
    for (String part : s.split("[_.\\-]")) {
      if (!part.isEmpty()) {
        b.append(upperFirst(part));
      }
    }
    return b.toString();
  }

  private static String upperFirst(String s) {
    return Character.toUpperCase(s.charAt(0)) + s.substring(1);
  }

  private static boolean isJavaKeyword(String s) {
    return Arrays.asList(
            "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class",
            "const", "continue", "default", "do", "double", "else", "enum", "extends", "final",
            "finally", "float", "for", "goto", "if", "implements", "import", "instanceof", "int",
            "interface", "long", "native", "new", "package", "private", "protected", "public",
            "return", "short", "static", "strictfp", "super", "switch", "synchronized", "this",
            "throw", "throws", "transient", "try", "void", "volatile", "while")
        .contains(s);
  }
